#!/usr/bin/env python3
"""Update the lightweight index without instantiating lazy settings pages."""
import json
import re
from pathlib import Path

components = Path(__file__).resolve().parents[1] / 'qml/decodium/components'
entries = [[1, 'Radio and audio troubleshooting']]
for tab in range(14):
    source = (components / f'SettingsTab{tab}.qml').read_text(encoding='utf-8')
    seen = set()
    for raw in re.findall(r'(?<![.\w])(?:text|placeholderText)\s*:\s*qsTr\("((?:[^"\\]|\\.)*)"\)', source):
        try:
            label = json.loads('"' + raw + '"')
        except ValueError:
            continue
        if len(label) < 3 or len(label) > 110 or '%' in label or label in seen:
            continue
        seen.add(label)
        entries.append([tab, label])
prefix = '''// Generated by scripts/update_settings_search.py.\n.pragma library\nvar entries = '''
suffix = ''';\nfunction find(query) {\n    var words = query.toLocaleLowerCase().trim().split(/\\s+/);\n    if (!query.trim()) return [];\n    var result = [];\n    for (var i = 0; i < entries.length; ++i) {\n        var e = entries[i], translated = qsTranslate("SettingsTab" + e[0], e[1]);\n        var haystack = (translated + " " + e[1]).toLocaleLowerCase();\n        if (words.every(function(word) { return haystack.indexOf(word) >= 0; }))\n            result.push({tab:e[0], label:translated});\n        if (result.length >= 80) break;\n    }\n    return result;\n}\n'''
(components / 'SettingsSearchIndex.js').write_text(prefix + json.dumps(entries, ensure_ascii=False, separators=(',', ':')) + suffix, encoding='utf-8')
